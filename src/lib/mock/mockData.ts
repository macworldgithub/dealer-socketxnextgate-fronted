export function calculateLeadStats(customers: CustomerLeadRecord[]): LeadStats {
  const total = customers.length;
  const newLeads = customers.filter(
    (c) => c.lead.stage?.toLowerCase() === 'new'
  ).length;
  const contacted = customers.filter(
    (c) => c.lead.stage?.toLowerCase() === 'contacted'
  ).length;
  const inProgress = customers.filter(
    (c) =>
      ['contacted', 'test drive', 'negotiation', 'in progress'].includes(
        c.lead.stage?.toLowerCase() || ''
      )
  ).length;
  const closedWon = customers.filter(
    (c) => c.lead.stage?.toLowerCase() === 'won' || c.lead.stage?.toLowerCase() === 'closed won'
  ).length;
  const multiEnquiriesCount = customers.filter(
    (c) => c.leadCount > 1 || c.lead.multipleVehicleEnquiries
  ).length;

  return {
    total,
    newLeads,
    contacted,
    inProgress,
    closedWon,
    multiEnquiriesCount,
  };
}
